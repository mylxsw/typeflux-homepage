export function accountCopy(lang) {
  return copies[lang] || copies.en
}

// accountText resolves a dotted key such as "handoff.switchNote".
export function accountText(lang, key, values) {
  const value = key.split('.').reduce((node, part) => node?.[part], accountCopy(lang))
  return formatMessage(value ?? key, values)
}

